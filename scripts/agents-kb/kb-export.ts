#!/usr/bin/env node
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import { DATA_DIR, kbPath, SCRIPTS_DIR } from './kb-config.ts';
import { createConsoleLogger, createLogger, type KbLogger } from './kb-log.ts';

export interface ExportResult {
  outPath: string;
  count: number;
}

function exportPath(): string {
  return process.env.AGENTS_KB_EXPORT_PATH
    ? path.resolve(process.env.AGENTS_KB_EXPORT_PATH)
    : path.join(SCRIPTS_DIR, 'kb-export.md');
}

/**
 * DB -> deterministic metadata report. The DB holds no content, so this exports
 * only registry metadata (kind/key/path/title/status/tags/hash/source) for review,
 * diffing, and sharing. Filesystem content is never regenerated.
 */
export async function runExport(logger?: KbLogger): Promise<ExportResult> {
  const log = logger ?? createConsoleLogger();
  log.section('export');

  const dbFile = kbPath();
  const lines: string[] = [];
  lines.push('# Agents Knowledge Base — Metadata Export');
  lines.push('');
  lines.push('> Auto-generated by `scripts/agents-kb/kb-export.ts`. Deterministic: re-running');
  lines.push('> produces an identical file. The DB stores metadata only; filesystem content is canonical.');
  lines.push('');

  let count = 0;
  if (!existsSync(dbFile)) {
    log.warn(`database not found: ${dbFile} — writing empty report`);
    lines.push('_No database present. Run `npm run setup` then `npm run sync` to populate._');
    lines.push('');
  } else {
    const db = new DatabaseSync(dbFile);
    db.exec('PRAGMA foreign_keys = ON;');
    try {
      const rows = db
        .prepare(
          `SELECT artifact_id, org_slug, kind, key, path_rel, title, status, applies_to, tags,
                  content_hash, source, deleted_at
           FROM artifacts WHERE deleted_at IS NULL ORDER BY path_rel ASC, kind ASC, key ASC`
        )
        .all() as Array<Record<string, unknown>>;

      lines.push(`## Registry (${rows.length} artifacts)`);
      lines.push('');
      lines.push('| Kind | Key | Path | Title | Status | Tags | Hash | Source |');
      lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
      for (const r of rows) {
        const tags = safeJsonArray(r.tags);
        const hash = String(r.content_hash ?? '').slice(0, 12);
        lines.push(
          `| ${esc(String(r.kind ?? ''))} | ${esc(String(r.key ?? ''))} | ${esc(String(r.path_rel ?? ''))} | ` +
            `${esc(String(r.title ?? ''))} | ${esc(String(r.status ?? ''))} | ${esc(tags.join(', '))} | ` +
            `${hash} | ${esc(String(r.source ?? ''))} |`
        );
        count += 1;
      }
      lines.push('');

      // metadata_entries (if any)
      const metaRows = db
        .prepare(
          `SELECT m.meta_key, m.meta_value, m.value_type, a.path_rel
           FROM metadata_entries m JOIN artifacts a ON a.artifact_id = m.artifact_id
           WHERE a.deleted_at IS NULL ORDER BY a.path_rel ASC, m.meta_key ASC`
        )
        .all() as Array<Record<string, unknown>>;
      if (metaRows.length > 0) {
        lines.push(`## Metadata entries (${metaRows.length})`);
        lines.push('');
        lines.push('| Path | Key | Value | Type |');
        lines.push('| --- | --- | --- | --- |');
        for (const m of metaRows) {
          lines.push(
            `| ${esc(String(m.path_rel ?? ''))} | ${esc(String(m.meta_key ?? ''))} | ` +
              `${esc(String(m.meta_value ?? ''))} | ${esc(String(m.value_type ?? ''))} |`
          );
        }
        lines.push('');
      }
    } catch (err) {
      log.warn(`query failed: ${err instanceof Error ? err.message : String(err)}`);
    } finally {
      try {
        db.close();
      } catch {
        // ignore
      }
    }
  }

  const content = lines.join('\n') + '\n';
  const outPath = exportPath();
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  await fs.writeFile(outPath, content, 'utf8');
  log.log(`export written: ${outPath} (${count} artifacts)`);
  return { outPath, count };
}

function safeJsonArray(v: unknown): string[] {
  if (typeof v !== 'string' || v.trim() === '') return [];
  try {
    const parsed = JSON.parse(v);
    return Array.isArray(parsed) ? parsed.map(x => String(x)) : [];
  } catch {
    return [];
  }
}

function esc(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

// Direct-run guard: only auto-run when this file is the CLI entry point.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const logger = createLogger('export');
  runExport(logger)
    .then(result => {
      logger.log(`export complete: ${result.outPath} (${result.count} artifacts)`);
      logger.close();
    })
    .catch(err => {
      logger.error(err instanceof Error ? (err.stack ?? err.message) : String(err));
      logger.close();
      process.exit(1);
    });
}
